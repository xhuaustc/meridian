#[derive(serde::Deserialize)]
struct UpstreamTarget {
    host: String,
    port: u16,
    weight: Option<u32>,
}

/// Parse the upstream_targets JSON field into a list of targets.
fn parse_upstream_targets(json: &str) -> Option<Vec<UpstreamTarget>> {
    serde_json::from_str::<Vec<UpstreamTarget>>(json)
        .ok()
        .filter(|v| !v.is_empty())
}

fn effective_upstream_targets(rule: &ProxyRule) -> Option<Vec<UpstreamTarget>> {
    if let Some(targets) = rule
        .upstream_targets
        .as_deref()
        .and_then(parse_upstream_targets)
    {
        return Some(targets);
    }

    if rule.keep_alive {
        return Some(vec![UpstreamTarget {
            host: rule.upstream_host.clone(),
            port: rule.upstream_port,
            weight: None,
        }]);
    }

    None
}

/// Generate a stable upstream block name from a rule id.
fn upstream_name(rule_id: &str) -> String {
    // Use last 12 chars of UUID to keep it short but unique
    let short = if rule_id.len() > 12 {
        &rule_id[rule_id.len() - 12..]
    } else {
        rule_id
    };
    format!("upstream_{}", short.replace('-', "_"))
}

/// Generate an nginx HTTP server block for one or more rules sharing the same port+domain.
///
/// `hostname_settings` carries the per-hostname overrides for the response
/// headers; a hostname without a row keeps all three default headers on and
/// HSTS off. `Strict-Transport-Security` is only added when this block
/// terminates TLS *and* the hostname's row turns HSTS on.
pub fn generate_server_block(
    rules: &[&ProxyRule],
    certs: &[Certificate],
    access_lists: &[(AccessList, Vec<AccessRule>)],
    data_dir: &Path,
    hostname_settings: &HashMap<String, HostnameSettings>,
    request_defaults: &RequestDefaults,
) -> String {
    if rules.is_empty() {
        return String::new();
    }

    let first = rules[0];
    let listen_port = first.listen_port;
    let domain = first.domain.as_deref().unwrap_or("_");

    let mut out = String::new();
    out.push_str("# Auto-generated by Meridian. Do not edit manually.\n");

    // Generate upstream blocks for load balancing or upstream keep-alive.
    for rule in rules {
        if let Some(targets) = effective_upstream_targets(rule) {
            let name = upstream_name(&rule.id);
            out.push_str(&format!("upstream {} {{\n", name));
            for t in &targets {
                let weight_str = t.weight.map_or(String::new(), |w| format!(" weight={}", w));
                out.push_str(&format!(
                    "    server {}:{}{};\n",
                    t.host, t.port, weight_str
                ));
            }
            if rule.keep_alive {
                out.push_str("    keepalive 32;\n");
            }
            out.push_str("}\n\n");
        }
    }
    out.push_str("server {\n");

    // Listen directive
    let has_tls = first.tls_mode == "terminate";
    if has_tls {
        out.push_str(&format!("    listen {} ssl;\n", listen_port));
    } else {
        out.push_str(&format!("    listen {};\n", listen_port));
    }

    out.push_str(&format!("    server_name {};\n", domain));

    // TLS certificate
    if has_tls {
        if let Some(cert_id) = &first.certificate_id {
            if let Some(cert) = certs.iter().find(|c| &c.id == cert_id) {
                out.push_str(&format!(
                    "    ssl_certificate \"{}\";\n",
                    nginx_path_str(&cert.cert_path)
                ));
                out.push_str(&format!(
                    "    ssl_certificate_key \"{}\";\n",
                    nginx_path_str(&cert.key_path)
                ));
                out.push_str("    ssl_protocols TLSv1.2 TLSv1.3;\n");
                out.push_str("    ssl_prefer_server_ciphers on;\n");
            }
        }
    }

    // TLS passthrough is handled at stream level, but add a comment
    if first.tls_mode == "passthrough" {
        out.push_str("    # TLS passthrough - should use stream block instead\n");
    }

    // Default security response headers. One function produces the complete
    // list and this is the only place that expands it. `always` keeps the
    // headers on error responses, including the 502 page below, and the list
    // stays at server level so no `location` can drop it. Passthrough rules are
    // forwarded at stream level, where nginx never sees the HTTP response, so
    // they deliberately carry no response headers.
    if first.tls_mode != "passthrough" {
        let headers = security_headers::response_headers(
            hostname_settings.get(domain),
            security_headers::ResponseContext {
                tls_terminated: has_tls,
            },
        );
        if !headers.is_empty() {
            out.push('\n');
            out.push_str(
                "    # Security response headers; `always` also covers error responses.\n",
            );
            for header in headers {
                let always = if header.applies_to_error_responses {
                    " always"
                } else {
                    ""
                };
                let value = if header.quote_value {
                    format!("\"{}\"", header.value)
                } else {
                    header.value
                };
                out.push_str(&format!(
                    "    add_header {} {}{};\n",
                    header.name, value, always
                ));
            }
        }
    }

    out.push('\n');

    // Custom error pages
    out.push_str("    proxy_intercept_errors on;\n");
    out.push_str("    error_page 502 /502.html;\n");
    let html_dir = data_dir.join("nginx/html");
    out.push_str(&format!(
        "    location = /502.html {{\n        root \"{}\";\n        internal;\n    }}\n\n",
        nginx_path(&html_dir)
    ));

    // Location blocks for each rule
    for rule in rules {
        let path = rule.path_prefix.as_deref().unwrap_or("/");
        out.push_str(&format!("    location {} {{\n", path));

        // Per-rule access log for monitoring metrics (JSON format)
        let rule_log = data_dir.join(format!("nginx/logs/rule_{}.access.log", rule.id));
        out.push_str(&format!(
            "        access_log \"{}\" meridian;\n",
            nginx_path(&rule_log)
        ));
        // Keep global access log (location-level access_log overrides http-level inheritance)
        let global_log = data_dir.join("nginx/logs/access.log");
        out.push_str(&format!(
            "        access_log \"{}\";\n",
            nginx_path(&global_log)
        ));

        // Determine proxy_pass target: upstream block or single host
        let scheme = &rule.upstream_scheme;
        let has_upstream = effective_upstream_targets(rule).is_some();
        if has_upstream {
            let name = upstream_name(&rule.id);
            out.push_str(&format!("        proxy_pass {}://{};\n", scheme, name));
        } else {
            out.push_str(&format!(
                "        proxy_pass {}://{}:{};\n",
                scheme, rule.upstream_host, rule.upstream_port
            ));
        }

        out.push_str("        proxy_set_header Host $host;\n");
        out.push_str("        proxy_set_header X-Real-IP $remote_addr;\n");
        out.push_str("        proxy_set_header X-Forwarded-For $proxy_add_x_forwarded_for;\n");
        out.push_str("        proxy_set_header X-Forwarded-Proto $scheme;\n");

        // WebSocket support
        if rule.websocket {
            out.push_str("        proxy_http_version 1.1;\n");
            out.push_str("        proxy_set_header Upgrade $http_upgrade;\n");
            out.push_str("        proxy_set_header Connection \"upgrade\";\n");
        } else if rule.keep_alive {
            out.push_str("        proxy_http_version 1.1;\n");
            out.push_str("        proxy_set_header Connection \"\";\n");
        }

        // Custom headers
        if let Some(headers_json) = &rule.custom_headers {
            if let Ok(headers) =
                serde_json::from_str::<std::collections::HashMap<String, String>>(headers_json)
            {
                for (key, value) in &headers {
                    out.push_str(&format!("        proxy_set_header {} {};\n", key, value));
                }
            }
        }

        // Request parameters: every location spells out the effective value, so
        // inheriting from the global defaults is still visible in the file that
        // nginx actually reads.
        for param in RequestParam::ALL {
            out.push_str(&format!(
                "        {} {};\n",
                param.directive(),
                request_params::effective(&rule.request, request_defaults, param)
            ));
        }

        // Keep access rules local to this location so unrelated paths do not inherit them.
        if let Some(acl_id) = &rule.access_list_id {
            if let Some((acl, acl_rules)) = access_lists.iter().find(|(l, _)| &l.id == acl_id) {
                out.push_str(&generate_access_directives(acl, acl_rules, "        "));
            }
        }

        out.push_str("    }\n\n");
    }

    out.push_str("}\n");
    out
}

/// Port the synthesised HTTP -> HTTPS redirect block listens on.
pub const REDIRECT_LISTEN_PORT: u16 = 80;

/// Why a synthesised redirect block is not emitted.
#[derive(Debug, Clone, Copy, PartialEq, Eq, serde::Serialize)]
pub enum ForceHttpsSkip {
    /// Another enabled rule already serves port 80 for this hostname.
    #[serde(rename = "existing_port_80_rule")]
    ExistingPort80Rule,
    /// The rule itself listens on port 80, where the redirect would live.
    #[serde(rename = "own_port_80")]
    OwnPort80,
}

/// Whether a rule asks for a synthesised HTTP -> HTTPS redirect.
///
/// The stored flag only means something for an HTTP rule that terminates TLS:
/// without an HTTPS endpoint there is nothing to redirect to.
pub fn wants_https_redirect(rule: &ProxyRule) -> bool {
    rule.proxy_type == "http"
        && rule.tls_mode == "terminate"
        && rule.force_https
        && rule
            .domain
            .as_deref()
            .is_some_and(|domain| !domain.is_empty())
}

/// Whether the synthesised redirect block would be generated for a rule.
///
/// The block is a generation artefact with no row behind it, so the form cannot
/// derive this itself without duplicating the generator's rules.
#[derive(Debug, Clone, serde::Serialize)]
pub struct ForceHttpsCheck {
    /// True when config generation would emit the redirect block.
    pub synthesized: bool,
    /// Why it is skipped; `None` when `synthesized` is true.
    pub skipped: Option<ForceHttpsSkip>,
    /// Name of the rule that already serves port 80, when that is the reason.
    pub blocking_rule_name: Option<String>,
}

/// The enabled rule that already serves port 80 for `domain`, if any.
fn port_80_rule<'a>(
    rules: &'a [ProxyRule],
    domain: &str,
    exclude_id: Option<&str>,
) -> Option<&'a ProxyRule> {
    rules.iter().find(|rule| {
        rule.proxy_type == "http"
            && rule.listen_port == REDIRECT_LISTEN_PORT
            && rule.domain.as_deref() == Some(domain)
            && exclude_id.is_none_or(|excluded| rule.id != excluded)
    })
}

/// Decide whether a rule would get a synthesised redirect block, given the
/// other enabled rules. Must agree with what config generation does, because
/// the form shows the outcome before the rule is saved.
pub fn check_force_https(
    rules: &[ProxyRule],
    domain: &str,
    listen_port: u16,
    exclude_id: Option<&str>,
) -> ForceHttpsCheck {
    if listen_port == REDIRECT_LISTEN_PORT {
        return ForceHttpsCheck {
            synthesized: false,
            skipped: Some(ForceHttpsSkip::OwnPort80),
            blocking_rule_name: None,
        };
    }
    match port_80_rule(rules, domain, exclude_id) {
        Some(blocking) => ForceHttpsCheck {
            synthesized: false,
            skipped: Some(ForceHttpsSkip::ExistingPort80Rule),
            blocking_rule_name: Some(blocking.name.clone()),
        },
        None => ForceHttpsCheck {
            synthesized: true,
            skipped: None,
            blocking_rule_name: None,
        },
    }
}

/// Generate the synthesised HTTP -> HTTPS redirect server block for a hostname.
///
/// This block is a generation artefact: no `proxy_rules` row represents it, so
/// it never shows up in the rule list, the rule counts or conflict detection.
/// The orchestrator appends it to the hostname's own `conf.d/{port}_{domain}.conf`
/// file, which keeps the generated-file naming scheme intact. `return 308` sends
/// the client to HTTPS while keeping the original method and body.
pub fn generate_https_redirect_block(hostname: &str) -> String {
    let mut out = String::new();
    out.push_str("# Auto-generated by Meridian: HTTP -> HTTPS redirect. Do not edit manually.\n");
    out.push_str("server {\n");
    out.push_str(&format!("    listen {};\n", REDIRECT_LISTEN_PORT));
    out.push_str(&format!("    server_name {};\n", hostname));
    out.push_str("    return 308 https://$host$request_uri;\n");
    out.push_str("}\n");
    out
}

fn generate_access_directives(acl: &AccessList, rules: &[AccessRule], indent: &str) -> String {
    let mut out = String::new();
    for rule in rules {
        let directive = if rule.action == "allow" {
            "allow"
        } else {
            "deny"
        };
        out.push_str(&format!("{}{} {};\n", indent, directive, rule.ip_cidr));
    }
    let default = if acl.default_policy == "allow" {
        "allow all"
    } else {
        "deny all"
    };
    out.push_str(&format!("{}{};\n", indent, default));
    out
}

