    #[test]
    fn force_https_check_serialises_the_contract_the_form_reads() {
        assert_eq!(
            serde_json::to_string(&ForceHttpsSkip::ExistingPort80Rule).unwrap(),
            "\"existing_port_80_rule\""
        );
        assert_eq!(
            serde_json::to_string(&ForceHttpsSkip::OwnPort80).unwrap(),
            "\"own_port_80\""
        );

        let check = check_force_https(&[], "app.local", 443, None);
        let json = serde_json::to_value(&check).unwrap();
        assert_eq!(json["synthesized"], true);
        assert!(json["skipped"].is_null());
        assert!(json["blocking_rule_name"].is_null());
    }
