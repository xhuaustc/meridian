use std::path::Path;

use super::nginx_path;
use crate::nginx_manager::Capabilities;

/// Generate the main nginx.conf content.
///
/// `worker_processes` controls the number of nginx worker processes.
/// Accepts "auto" or a numeric string (e.g. "2"). Defaults to "2".
///
/// `capabilities` decides which directives are safe to emit: a build without the
/// HTTP/2 module rejects `http2 on;` outright, so the directive is omitted
/// rather than emitted and left to fail at `nginx -t` time.
pub fn generate_main_config(
    data_dir: &Path,
    worker_processes: &str,
    capabilities: Capabilities,
) -> String {
    let dir = nginx_path(data_dir);
    // Validate: must be "auto" or a positive integer
    let wp = if worker_processes == "auto" {
        "auto".to_string()
    } else {
        worker_processes
            .parse::<u32>()
            .unwrap_or(2)
            .max(1)
            .to_string()
    };
    let http2_directive = if capabilities.http2 {
        "\n    http2 on;"
    } else {
        ""
    };
    format!(
        r#"# Auto-generated by Meridian. Do not edit manually.
worker_processes {wp};
pid "{dir}/nginx/nginx.pid";
error_log "{dir}/nginx/logs/error.log";

events {{
    worker_connections 1024;
}}

http {{
    # Temp directories (override compile-time defaults)
    client_body_temp_path "{dir}/nginx/temp/client_body";
    proxy_temp_path "{dir}/nginx/temp/proxy";

    log_format meridian escape=json
      '{{"time":"$time_iso8601",'
      '"remote_addr":"$remote_addr",'
      '"method":"$request_method",'
      '"uri":"$request_uri",'
      '"status":$status,'
      '"body_bytes_sent":$body_bytes_sent,'
      '"request_time":$request_time,'
      '"upstream_response_time":"$upstream_response_time",'
      '"host":"$host",'
      '"server_protocol":"$server_protocol"}}';

    access_log "{dir}/nginx/logs/access.log";

    sendfile on;
    tcp_nopush on;
    tcp_nodelay on;
    keepalive_timeout 65;
    types_hash_max_size 2048;
    client_max_body_size 100m;{http2_directive}

    # MIME types
    default_type application/octet-stream;

    include "{dir}/nginx/conf.d/*.conf";
}}

stream {{
    log_format stream_meridian
      '{{"time":"$time_iso8601",'
      '"remote_addr":"$remote_addr",'
      '"protocol":"$protocol",'
      '"status":$status,'
      '"bytes_sent":$bytes_sent,'
      '"bytes_received":$bytes_received,'
      '"session_time":"$session_time"}}';

    include "{dir}/nginx/stream.d/*.conf";
}}
"#,
        dir = dir,
    )
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::path::PathBuf;

    use crate::config_engine::test_support::SidecarHarness;

    #[test]
    fn test_main_config_has_required_sections() {
        let data_dir = PathBuf::from("/tmp/test");
        let config = generate_main_config(&data_dir, "2", Capabilities::default());
        assert!(config.contains("worker_processes 2;"));
        assert!(config.contains("http {"));
        assert!(config.contains("stream {"));
        assert!(config.contains("include"));
        assert!(config.contains("conf.d/*.conf"));
        assert!(config.contains("stream.d/*.conf"));
    }

    #[test]
    fn test_main_config_has_json_log_format() {
        let data_dir = PathBuf::from("/tmp/test");
        let config = generate_main_config(&data_dir, "auto", Capabilities::default());
        assert!(config.contains("worker_processes auto;"));
        assert!(config.contains("log_format"));
        assert!(config.contains("meridian"));
    }

    #[test]
    fn test_main_config_emits_no_response_headers() {
        let data_dir = PathBuf::from("/tmp/test");
        let config = generate_main_config(&data_dir, "2", Capabilities::default());
        assert!(
            !config.contains("add_header"),
            "security headers belong to each server block, never the http level: \
             an http-level directive would leak onto every hostname and passthrough server"
        );
    }

    #[test]
    fn test_main_config_enables_http2_when_the_build_supports_it() {
        let data_dir = PathBuf::from("/tmp/test");
        let config = generate_main_config(
            &data_dir,
            "2",
            Capabilities {
                probed: true,
                http2: true,
            },
        );
        assert!(config.contains("http2 on;"));
    }

    #[test]
    fn test_main_config_omits_http2_when_the_build_lacks_the_module() {
        let data_dir = PathBuf::from("/tmp/test");
        let config = generate_main_config(
            &data_dir,
            "2",
            Capabilities {
                probed: true,
                http2: false,
            },
        );
        assert!(!config.contains("http2"));
    }

    #[test]
    fn test_main_config_omits_http2_when_the_probe_failed() {
        let data_dir = PathBuf::from("/tmp/test");
        let config = generate_main_config(&data_dir, "2", Capabilities::default());
        assert!(!config.contains("http2"));
    }

    /// What the shipped binary advertises and what the generator emits must
    /// agree, and the result must still be valid configuration. Skips (loudly)
    /// when the sidecar has not been built on this machine.
    #[test]
    fn test_generated_main_config_matches_what_the_sidecar_supports() {
        let Some((config, capabilities)) = SidecarHarness::with_configs(|harness| {
            let capabilities = harness.capabilities();
            assert!(
                capabilities.probed,
                "sidecar did not report a configure line"
            );
            let config = harness.write_main_config("1", capabilities);
            (config, capabilities)
        }) else {
            return;
        };

        assert_eq!(
            config.contains("http2 on;"),
            capabilities.http2,
            "generator and probe disagree about HTTP/2 support"
        );
    }

    /// A build without HTTP/2 must still produce config the engine accepts:
    /// the directive is omitted rather than emitted and left to fail.
    #[test]
    fn test_config_without_http2_is_still_accepted_by_the_sidecar() {
        let Some(config) = SidecarHarness::with_configs(|harness| {
            harness.write_main_config(
                "1",
                Capabilities {
                    probed: true,
                    http2: false,
                },
            )
        }) else {
            return;
        };

        assert!(!config.contains("http2"));
    }

    #[test]
    fn test_main_config_logs_the_protocol_served_to_clients() {
        let data_dir = PathBuf::from("/tmp/test");
        let config = generate_main_config(&data_dir, "2", Capabilities::default());
        assert!(config.contains("\"server_protocol\":\"$server_protocol\""));
    }
}
